object AppLanguageManager {
    private const val PREFS_NAME = "smart_bill_language_prefs"
    private const val KEY_LANG = "selected_language"

    private lateinit var prefs: SharedPreferences
    private val _currentLanguage = MutableStateFlow("en")
    val currentLanguage: StateFlow<String> = _currentLanguage.asStateFlow()

    fun init(context: Context) {
        prefs = context.getSharedPreferences(PREFS_NAME, Context.MODE_PRIVATE)
        val saved = prefs.getString(KEY_LANG, "en") ?: "en"
        _currentLanguage.value = saved
    }

    fun setLanguage(langCode: String) {
        _currentLanguage.value = langCode
        if (::prefs.isInitialized) {
            prefs.edit().putString(KEY_LANG, langCode).apply()
        }
    }

    fun getLanguage(): String = _currentLanguage.value

    @Composable
    fun getString(key: String): String {
        val lang by currentLanguage.collectAsState()
        return getTranslation(key, lang)
    }

    fun tr(key: String, lang: String = _currentLanguage.value): String {
        return getTranslation(key, lang)
    }

    private fun getTranslation(key: String, lang: String): String {
        val dict = TRANSLATIONS[lang] ?: TRANSLATIONS["en"] ?: emptyMap()
        return dict[key] ?: TRANSLATIONS["en"]?.get(key) ?: key
    }

